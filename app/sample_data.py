def autocomplete_text(document: dict[str, Any]) -> str:
    parts = [
        document["provider_name"],
        document["specialty_name"],
        *document["aliases"],
        *document["conditions"],
        *document["procedures"],
        *document["splunk_user_keywords"],
    ]
    return " ".join(parts)


def prepared_sample_documents() -> list[dict[str, Any]]:
    documents = deepcopy(SAMPLE_PROVIDERS)
    for index, document in enumerate(documents):
        document["document_type"] = "care_provider"
        longitude, latitude = ZIP_COORDINATES[document["zip"]]
        document["location"] = {"type": "Point", "coordinates": [longitude, latitude]}
        document["map_label"] = f"{document['city']}, {document['state']} {document['zip']}"
        document["address_line1"] = f"{120 + (index * 73) % 8800} {STREET_NAMES[index % len(STREET_NAMES)]}"
        document["phone"] = f"(512) 555-{100 + index:04d}"
        document["next_available"] = (
            NEXT_AVAILABLE[index % len(NEXT_AVAILABLE)]
            if document["accepting_new_patients"]
            else "Call for availability"
        )
        document["specialty_filter"] = document["specialty_name"]
        document["networks_filter"] = list(document["insurance_networks"])
        document["languages_filter"] = list(document["languages"])
        document["autocomplete_text"] = autocomplete_text(document)
        document["embedding_text"] = (
            f"{document['provider_name']} is a {document['specialty_name']} option in "
            f"{document['city']}, {document['state']}. {document['care_summary']} "
            f"Common searches include {', '.join(document['splunk_user_keywords'])}. "
            f"Conditions: {', '.join(document['conditions'])}. "
            f"Procedures: {', '.join(document['procedures'])}."
        )
    return documents
